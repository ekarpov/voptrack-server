// language picks from an explicit choice first, then the browser's list.
// Release one is English-only. Keep languages and all catalogs intact for the
// deferred localization release, including their completeness checks.
func language(_ *http.Request, _ string) string { return "en" }

func translator(lang string) func(string) string {
	return func(key string) string {
		if s, ok := messages[lang][key]; ok {
			return s
		}
		if s, ok := messages["en"][key]; ok {
			return s
		}
		return key
	}
}
